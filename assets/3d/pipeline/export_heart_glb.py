"""Write the labelled heart parts (from segment_heart.py) to an uncompressed GLB.

Units: decimetres (1 unit = 10 cm), origin at the centroid of the heart muscle, axes
+x = patient's left, +y = superior, +z = anterior (same as the scene and the body mesh).
The model is scaled so the apex-to-aortic-root distance is 12 cm (typical adult heart).
"""
from __future__ import annotations

import json
import struct
from pathlib import Path

import numpy as np

BUILD = Path(__file__).resolve().parents[1] / "build"
LANDMARKS = Path(__file__).resolve().parents[3] / "frontend" / "src" / "config" / "anatomy.landmarks.json"
TRUNK_POINTS = 48  # samples per vessel trunk in the landmark file
APEX_TO_ROOT_DM = 1.2


def write_glb(path: Path, parts: dict[str, tuple[np.ndarray, np.ndarray]], extras: dict) -> None:
    bin_chunks, views, accessors, meshes, nodes = [], [], [], [], []
    offset = 0

    def add_view(data: bytes, target: int) -> int:
        nonlocal offset
        pad = (-len(data)) % 4
        bin_chunks.append(data + b"\0" * pad)
        views.append({"buffer": 0, "byteOffset": offset, "byteLength": len(data), "target": target})
        offset += len(data) + pad
        return len(views) - 1

    for name, (P, T) in parts.items():
        pv = add_view(P.astype("<f4").tobytes(), 34962)
        iv = add_view(T.astype("<u4").ravel().tobytes(), 34963)
        accessors.append({"bufferView": pv, "componentType": 5126, "count": len(P), "type": "VEC3",
                          "min": P.min(0).tolist(), "max": P.max(0).tolist()})
        accessors.append({"bufferView": iv, "componentType": 5125, "count": T.size, "type": "SCALAR"})
        meshes.append({"name": name, "primitives": [{"attributes": {"POSITION": len(accessors) - 2}, "indices": len(accessors) - 1}]})
        nodes.append({"name": name, "mesh": len(meshes) - 1})

    blob = b"".join(bin_chunks)
    gltf = {"asset": {"version": "2.0", "generator": "cardioscope export_heart_glb.py"},
            "scene": 0, "scenes": [{"nodes": list(range(len(nodes))), "extras": extras}],
            "nodes": nodes, "meshes": meshes, "accessors": accessors, "bufferViews": views,
            "buffers": [{"byteLength": len(blob)}]}
    js = json.dumps(gltf, separators=(",", ":")).encode()
    js += b" " * ((-len(js)) % 4)
    with open(path, "wb") as fh:
        fh.write(struct.pack("<III", 0x46546C67, 2, 12 + 8 + len(js) + 8 + len(blob)))
        fh.write(struct.pack("<II", len(js), 0x4E4F534A) + js)
        fh.write(struct.pack("<II", len(blob), 0x004E4942) + blob)


def main() -> None:
    d = np.load(BUILD / "heart_parts.npz")
    V = d["V"].astype(np.float64)
    faces = {k[2:]: d[k] for k in d.files if k.startswith("F_")}
    trunks = {k[2:]: d[k] for k in d.files if k.startswith("T_")}

    heart_ids = np.unique(faces["heart"].ravel())
    centre = V[heart_ids].mean(0)
    aorta = V[np.unique(faces["aorta"].ravel())]
    root = aorta[aorta[:, 1] < np.percentile(aorta[:, 1], 10)].mean(0)
    apex = V[heart_ids][np.argmax(np.linalg.norm(V[heart_ids] - root, axis=1))]
    scale = APEX_TO_ROOT_DM / np.linalg.norm(apex - root)

    parts = {}
    for name, F in faces.items():
        used, inv = np.unique(F.ravel(), return_inverse=True)
        parts[name] = (((V[used] - centre) * scale).astype(np.float32), inv.reshape(F.shape).astype(np.uint32))
    # Vessel trunk centre-lines for the viewer (risk nodes, labels, camera focus). The trunk path
    # runs over the vessel surface, so each sample is pulled to the local centre by averaging the
    # vessel's vertices within 2.5 mm.
    from scipy.spatial import cKDTree

    landmarks = {}
    for vid, path in trunks.items():
        vessel_pts = V[np.unique(faces[vid].ravel())]
        tree = cKDTree(vessel_pts)
        pts = V[path]
        seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
        s = np.concatenate([[0], np.cumsum(seg)])
        samples = np.array([pts[np.searchsorted(s, x, side="right") - 1] for x in np.linspace(0, s[-1], TRUNK_POINTS)])
        radius = 0.25 / scale  # 2.5 mm in model units (scale = dm per model unit)
        centred = np.array([vessel_pts[tree.query_ball_point(p, radius)].mean(0) for p in samples])
        landmarks[vid] = {"trunk": ((centred - centre) * scale).round(4).tolist(), "length_cm": round(float(s[-1] * scale * 10), 1)}
    LANDMARKS.write_text(json.dumps({"_comment": "Generated by assets/3d/pipeline/export_heart_glb.py; do not edit.",
                                     "units": "dm", "apex": ((apex - centre) * scale).round(4).tolist(),
                                     "vessels": landmarks}, indent=1) + "\n", encoding="utf-8")
    print("landmarks:", {k: f"{v['length_cm']} cm" for k, v in landmarks.items()})

    out = BUILD / "heart_raw.glb"
    write_glb(out, parts, {"units": "dm", "apex": ((apex - centre) * scale).round(4).tolist()})
    print(f"wrote {out} ({out.stat().st_size / 1e6:.1f} MB), scale {scale:.3f} dm/unit,",
          {k: len(v[1]) for k, v in parts.items()})


if __name__ == "__main__":
    main()
